"""Append-only SQLite storage for institution discovery profiles."""
from __future__ import annotations

import json
import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import datetime, timedelta
from typing import Protocol

from macro_data_platform.config import Settings
from macro_data_platform.discovery.institution_sites import profile_fingerprint

MAX_PROFILE_BYTES = 2_097_152


class ProfileDocument(Protocol):
    def to_document(self) -> dict: ...


class InstitutionProfileStore:
    def __init__(self, settings: Settings):
        self.settings = settings
        settings.database_path.parent.mkdir(parents=True, exist_ok=True)
        with self._connect() as connection:
            version = connection.execute("PRAGMA user_version").fetchone()[0]
            if version not in {0, 2}:
                raise ValueError("unsupported history schema version")
            connection.executescript(
                """
                CREATE TABLE IF NOT EXISTS institution_profiles (
                    profile_id TEXT PRIMARY KEY,
                    institution_id TEXT NOT NULL,
                    verified_at TEXT NOT NULL,
                    document TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS profiles_by_institution
                    ON institution_profiles(institution_id, verified_at, profile_id);
                CREATE TRIGGER IF NOT EXISTS institution_profiles_no_update
                BEFORE UPDATE ON institution_profiles
                BEGIN
                    SELECT RAISE(ABORT, 'institution profiles are append-only');
                END;
                CREATE TRIGGER IF NOT EXISTS institution_profiles_no_delete
                BEFORE DELETE ON institution_profiles
                BEGIN
                    SELECT RAISE(ABORT, 'institution profiles are append-only');
                END;
                """
            )

    @contextmanager
    def _connect(self) -> Iterator[sqlite3.Connection]:
        connection = sqlite3.connect(self.settings.database_path, timeout=5)
        try:
            yield connection
        finally:
            connection.close()

    def save(self, profile: ProfileDocument | dict) -> str:
        document = profile.to_document() if hasattr(profile, "to_document") else dict(profile)
        if "profile_id" in document:
            raise ValueError("profile_id is generated by the store")
        institution_id = document.get("institution_id")
        verified_at = document.get("verified_at")
        if not isinstance(institution_id, str) or not institution_id.strip():
            raise ValueError("profile must have an institution_id")
        if not isinstance(verified_at, str) or not verified_at.strip():
            raise ValueError("profile must have a verified_at timestamp")
        try:
            timestamp = datetime.fromisoformat(verified_at)
        except ValueError as exc:
            raise ValueError("profile verified_at must be an ISO timestamp") from exc
        if timestamp.utcoffset() is None or timestamp.utcoffset() != timedelta(0):
            raise ValueError("profile verified_at must use UTC")
        profile_id = profile_fingerprint(document)
        stored_document = {**document, "profile_id": profile_id}
        encoded = json.dumps(
            stored_document, ensure_ascii=False, allow_nan=False, sort_keys=True, separators=(",", ":")
        )
        if len(encoded.encode("utf-8")) > MAX_PROFILE_BYTES:
            raise ValueError("institution profile exceeds the configured size limit")
        with self._connect() as connection:
            connection.execute("BEGIN IMMEDIATE")
            connection.execute(
                "INSERT OR IGNORE INTO institution_profiles(profile_id, institution_id, verified_at, document) "
                "VALUES (?, ?, ?, ?)",
                (profile_id, institution_id, verified_at, encoded),
            )
            existing = connection.execute(
                "SELECT document FROM institution_profiles WHERE profile_id=?", (profile_id,)
            ).fetchone()
            if existing is None or existing[0] != encoded:
                raise RuntimeError("profile identity collision")
            connection.commit()
        return profile_id

    def get(self, profile_id: str) -> dict:
        with self._connect() as connection:
            row = connection.execute(
                "SELECT document FROM institution_profiles WHERE profile_id=?", (profile_id,)
            ).fetchone()
        if row is None:
            raise KeyError("unknown institution profile")
        return json.loads(row[0])

    def for_institution(self, institution_id: str) -> list[dict]:
        with self._connect() as connection:
            rows = connection.execute(
                "SELECT document FROM institution_profiles WHERE institution_id=? "
                "ORDER BY verified_at, profile_id",
                (institution_id,),
            ).fetchall()
        return [json.loads(row[0]) for row in rows]
